export const inferMachineType = (asset: { machineType?: string; location?: string; name?: string }): string => {
  if (asset.machineType && asset.machineType.trim()) return asset.machineType.trim();
  const loc = (asset.location || '').toLowerCase();
  const name = (asset.name || '').toLowerCase();
  if (loc.includes('حقن') || name.includes('حقن')) return 'حقن';
  if (loc.includes('بودرة') || name.includes('بودرة')) return 'بودرة';
  if (loc.includes('حب') || name.includes('حب') || loc.includes('تحثير') || loc.includes('تعليب') || loc.includes('ضغط') || loc.includes('مضغوط') || name.includes('مضغوط')) return 'المضغوطات';
  if (loc.includes('شراب') || name.includes('شراب')) return 'شراب';
  if (loc.includes('مرهم') || loc.includes('مراهم') || name.includes('مرهم') || name.includes('مراهم')) return 'مراهم';
  if (loc.includes('صيانة') || loc.includes('مولد') || loc.includes('ورشة')) return 'صيانة ومرافق';
  if (loc.includes('تغليف') || name.includes('تغليف') || loc.includes('تعبئة') || name.includes('تعبئة')) return 'تعبئة وتغليف';
  return 'عام';
};

